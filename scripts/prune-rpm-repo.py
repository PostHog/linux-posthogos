#!/usr/bin/env python3
"""Prune superseded .rpm packages from a dnf repo directory.

Keeps the N newest versions of each (name, arch) and deletes older .rpm
files. The repodata (regenerated by createrepo_c from the current build on
each release) only ever references the latest version, so older .rpms are
orphans that just consume the Pages quota — the dnf analogue of
prune-pacman-repo.py / prune-deb-repo.py.

Walks the given directory recursively for *.rpm. No sidecar signatures to
clean up (an rpm's signature lives in its own header, not a separate file).

No external dependencies (no rpm): version ordering is a faithful port of
rpm's rpmvercmp (rpmio/rpmvercmp.c), including '~' (sorts before everything,
even end-of-string) and '^' (sorts after a bare version).
"""

import argparse
import functools
import os
import sys
from collections import defaultdict


def _is_alnum(c):
    return c.isalnum()


def rpmvercmp(a, b):
    """Faithful port of rpm's rpmvercmp() → -1 / 0 / 1."""
    if a == b:
        return 0
    ia, ib = 0, 0
    la, lb = len(a), len(b)
    while ia < la or ib < lb:
        # Skip separators (anything not alnum and not '~' / '^').
        while ia < la and not (_is_alnum(a[ia]) or a[ia] in "~^"):
            ia += 1
        while ib < lb and not (_is_alnum(b[ib]) or b[ib] in "~^"):
            ib += 1

        # '~' sorts before everything else, including end-of-string.
        at = ia < la and a[ia] == "~"
        bt = ib < lb and b[ib] == "~"
        if at or bt:
            if not at:
                return 1
            if not bt:
                return -1
            ia += 1
            ib += 1
            continue

        # '^' sorts after a bare version; if one side ended, the other wins.
        ac = ia < la and a[ia] == "^"
        bc = ib < lb and b[ib] == "^"
        if ac or bc:
            if ia >= la:
                return -1
            if ib >= lb:
                return 1
            if not ac:
                return 1
            if not bc:
                return -1
            ia += 1
            ib += 1
            continue

        # Ran out on either side → done with the segment loop.
        if not (ia < la and ib < lb):
            break

        # Grab a wholly-numeric or wholly-alpha segment from each side.
        if a[ia].isdigit():
            sa, sb = ia, ib
            while ia < la and a[ia].isdigit():
                ia += 1
            while ib < lb and b[ib].isdigit():
                ib += 1
            seg_a, seg_b = a[sa:ia], b[sb:ib]
            isnum = True
        else:
            sa, sb = ia, ib
            while ia < la and a[ia].isalpha():
                ia += 1
            while ib < lb and b[ib].isalpha():
                ib += 1
            seg_a, seg_b = a[sa:ia], b[sb:ib]
            isnum = False

        # Different segment types (one side empty): numeric beats alpha.
        if seg_b == "":
            return 1 if isnum else -1

        if isnum:
            seg_a = seg_a.lstrip("0")
            seg_b = seg_b.lstrip("0")
            if len(seg_a) > len(seg_b):
                return 1
            if len(seg_a) < len(seg_b):
                return -1
        # Lexical compare settles equal-length numeric and alpha segments.
        if seg_a < seg_b:
            return -1
        if seg_a > seg_b:
            return 1
        # Equal so far — continue to the next segment.

    # All segments equal; whichever still has characters left wins.
    a_left = ia < la
    b_left = ib < lb
    if a_left and not b_left:
        return 1
    if b_left and not a_left:
        return -1
    return 0


def rpm_evrcmp(va, vb):
    """Compare (version, release) pairs from rpm filenames (no epoch)."""
    vc = rpmvercmp(va[0], vb[0])
    if vc:
        return vc
    return rpmvercmp(va[1], vb[1])


def parse_rpm(filename):
    """Return (name, arch, (version, release)) or None.

    rpm filename: <name>-<version>-<release>.<arch>.rpm. version/release never
    contain '-', so rsplit('-', 2) is exact; <name> may contain '-'.
    """
    if not filename.endswith(".rpm"):
        return None
    stem = filename[: -len(".rpm")]
    base, _, arch = stem.rpartition(".")
    if not arch or not base:
        return None
    parts = base.rsplit("-", 2)
    if len(parts) != 3:
        return None
    name, version, release = parts
    return name, arch, (version, release)


def prune(directory, keep, dry_run):
    groups = defaultdict(list)  # (name, arch) -> [(evr, full_path)]
    for root, _dirs, files in os.walk(directory):
        for entry in files:
            parsed = parse_rpm(entry)
            if parsed is None:
                continue
            name, arch, evr = parsed
            groups[(name, arch)].append((evr, os.path.join(root, entry)))

    removed = []
    for (_name, _arch), items in sorted(groups.items()):
        # Newest first.
        items.sort(key=functools.cmp_to_key(lambda x, y: rpm_evrcmp(y[0], x[0])))
        for _evr, path in items[keep:]:
            removed.append(path)

    if not removed:
        print(f"Nothing to prune in {directory} (keep={keep}).")
        return removed

    verb = "Would remove" if dry_run else "Removing"
    print(f"{verb} {len(removed)} file(s) from {directory} (keep={keep}):")
    for path in sorted(removed):
        print(f"  {os.path.relpath(path, directory)}")
        if not dry_run:
            os.remove(path)
    return removed


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("directory", help="dnf repo dir to prune (walked for *.rpm)")
    ap.add_argument(
        "--keep",
        type=int,
        default=2,
        help="number of newest versions to keep per package (default: 2)",
    )
    ap.add_argument(
        "--dry-run",
        action="store_true",
        help="list what would be removed without deleting",
    )
    args = ap.parse_args()
    if not os.path.isdir(args.directory):
        sys.exit(f"error: not a directory: {args.directory}")
    if args.keep < 1:
        sys.exit("error: --keep must be >= 1")
    prune(args.directory, args.keep, args.dry_run)


if __name__ == "__main__":
    main()
