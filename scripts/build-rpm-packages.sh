#!/usr/bin/env bash
#
# Build .rpm equivalents of the portable PosthogOS packages and assemble a
# signed dnf/zypper repository, for Fedora / RHEL / openSUSE-family systems.
#
# Like the .deb builder, this repackages the already-built portable pacman
# packages (`posthogos-branding`, `posthogos-scripts`) rather than re-staging
# from overlay/ — one source of truth for the file layout. Both are noarch
# (data + shell scripts), so a single rpm serves every basearch.
#
# Inputs (env):
#   PKG_SRC_DIR          dir holding posthogos-*.pkg.tar.zst (default: out/pkgs)
#   RPM_OUT_DIR          dnf repo output dir                 (default: out/rpm)
#   POSTHOGOS_PKGVER     version, e.g. 0.2.0 (default: derived from git tag)
#   POSTHOGOS_PACKAGER_KEY      armored GPG secret key; signs rpms + repomd (optional)
#   POSTHOGOS_PACKAGER_KEY_FPR  fingerprint of that key (required if KEY set)
#
# Without a key the repo is unsigned (local dev; the user sets gpgcheck=0).
# CI always signs.
#
# Tooling: rpmbuild, rpm (--addsign), createrepo_c, gpg, zstd-aware tar.
# Intended to run in a Fedora environment (bin/build-rpm's container / CI),
# whose rpm toolchain is the most reliable for signing — not on macOS.

set -euo pipefail

log() { printf '==> %s\n' "$*"; }
die() { printf 'ERROR: %s\n' "$*" >&2; exit 1; }

# shellcheck source=lib/posthogos-pkg.sh
. "$(dirname "$0")/lib/posthogos-pkg.sh"

# Portable, non-Arch-specific packages only (same set as the .deb builder).
RPM_PACKAGES=(posthogos-branding posthogos-scripts)

PKG_SRC_DIR="${PKG_SRC_DIR:-out/pkgs}"
RPM_OUT_DIR="${RPM_OUT_DIR:-out/rpm}"

for tool in rpmbuild createrepo_c gpg tar; do
    command -v "$tool" >/dev/null 2>&1 || die "missing required tool: $tool"
done

# --- Version --------------------------------------------------------------
if [ -z "${POSTHOGOS_PKGVER:-}" ]; then
    v=$(git describe --tags --abbrev=0 2>/dev/null | sed 's/^v//' || true)
    [ -n "$v" ] || v="0.0.0~dev.$(git rev-parse --short HEAD 2>/dev/null || echo unknown)"
    POSTHOGOS_PKGVER="$v"
fi
# rpm Version forbids '-' but allows '~' (sorts before, for pre-releases) — the
# shared helper already maps pre-release separators to '~'. Release is 1.
RPM_VER="$(posthogos_upstream_version "$POSTHOGOS_PKGVER")"
RPM_REL=1
log "RPM version: ${RPM_VER}-${RPM_REL} (from POSTHOGOS_PKGVER=$POSTHOGOS_PKGVER)"

# --- Per-package spec metadata (Summary, weak deps) -----------------------
# No hard Requires (so dnf never refuses on a minimal box); parent themes /
# tools are weak deps. snap-pac is omitted (pacman-only).
rpm_meta() {
    case "$1" in
    posthogos-branding)
        echo "Summary:PosthogOS visual identity (icons, wallpapers, Plasma look-and-feel, fonts, sounds)"
        echo "Recommends:papirus-icon-theme"
        echo "Suggests:plasma-workspace"
        ;;
    posthogos-scripts)
        echo "Summary:PosthogOS system scripts (firstrun, snapper-init, toolkit-install, neohog)"
        echo "Recommends:posthogos-branding"
        echo "Suggests:snapper"
        echo "Suggests:btrfs-progs"
        echo "Suggests:fastfetch"
        ;;
    *) die "no rpm metadata for $1" ;;
    esac
}

# --- Build one noarch .rpm from a .pkg.tar.zst ----------------------------
build_one_rpm() {
    local pkg="$1" out_dir="$2"
    log "$pkg"

    local root top
    root=$(mktemp -d)
    top=$(mktemp -d)
    # Extract + strip metadata + relocate /usr/local/bin (shared with deb).
    # License stays at /usr/share/licenses/<pkg>/ — the rpm convention.
    stage_posthogos_pkg "$pkg" "$PKG_SRC_DIR" "$root" || die "staging $pkg failed"

    # %files list: every regular file + symlink (never bare dirs, which would
    # collide with filesystem-owned /usr/bin, /usr/share, …).
    local filelist="$top/files.list"
    ( cd "$root" && find . \( -type f -o -type l \) | sed 's/^\.//' ) > "$filelist"

    # Weak deps → spec lines.
    local summary="" weak=""
    while IFS=: read -r tag val; do
        case "$tag" in
            Summary) summary="$val" ;;
            *)       weak+="${tag}: ${val}"$'\n' ;;
        esac
    done < <(rpm_meta "$pkg")

    local spec="$top/$pkg.spec"
    cat > "$spec" <<EOF
# Generated by build-rpm-packages.sh — repackages the prebuilt files, no build.
%global __os_install_post %{nil}
%global debug_package %{nil}
# No %changelog (nothing to date a build from); use the build clock.
%global source_date_epoch_from_changelog 0
Name:           $pkg
Version:        $RPM_VER
Release:        $RPM_REL
Summary:        $summary
License:        MIT
URL:            https://github.com/posthog/linux-posthogos
BuildArch:      noarch
AutoReqProv:    no
${weak}
%description
$summary

%install
cp -a %{posthogos_stage}/. %{buildroot}/

%files -f %{posthogos_filelist}
EOF

    rpmbuild -bb "$spec" \
        --define "_topdir $top" \
        --define "posthogos_stage $root" \
        --define "posthogos_filelist $filelist" \
        >/dev/null

    install -d "$out_dir"
    local built
    built=$(find "$top/RPMS" -name "${pkg}-${RPM_VER}-${RPM_REL}.noarch.rpm" | head -n1)
    [ -n "$built" ] || die "rpmbuild produced no rpm for $pkg"
    cp "$built" "$out_dir/"
    log "  -> $out_dir/$(basename "$built")"
    rm -rf "$root" "$top"
}

# --- Assemble the dnf repo ------------------------------------------------
main() {
    command -v createrepo_c >/dev/null 2>&1 || die "createrepo_c not found"
    rm -rf "$RPM_OUT_DIR"
    install -d "$RPM_OUT_DIR"

    local pkg
    for pkg in "${RPM_PACKAGES[@]}"; do
        build_one_rpm "$pkg" "$RPM_OUT_DIR"
    done

    local signed=0
    if [ -n "${POSTHOGOS_PACKAGER_KEY:-}" ]; then
        [ -n "${POSTHOGOS_PACKAGER_KEY_FPR:-}" ] \
            || die "POSTHOGOS_PACKAGER_KEY set but POSTHOGOS_PACKAGER_KEY_FPR is not"
        signed=1
        log "Importing packager key ${POSTHOGOS_PACKAGER_KEY_FPR:0:8}…"
        export GNUPGHOME
        GNUPGHOME=$(mktemp -d); chmod 700 "$GNUPGHOME"
        echo "$POSTHOGOS_PACKAGER_KEY" | gpg --batch --import \
            || die "failed to import POSTHOGOS_PACKAGER_KEY (see gpg error above)"

        # Sign each rpm (gpgcheck=1). rpm shells out to gpg for the signature;
        # GNUPGHOME points it at the imported (passphrase-less) key.
        local rpmhome; rpmhome=$(mktemp -d)
        # %{__gpg} is the ABSOLUTE gpg path (rpm execv's argv[0] without a
        # PATH lookup, so a bare `gpg` fails to exec). The rpm default macro
        # erroneously follows it with a literal `gpg` token — drop that (it
        # was breaking arg parsing: "no command supplied"). Options first,
        # then the -s sign command and the files.
        cat > "$rpmhome/.rpmmacros" <<EOF
%_gpg_name $POSTHOGOS_PACKAGER_KEY_FPR
%__gpg_sign_cmd %{__gpg} --batch --no-verbose --no-armor --pinentry-mode loopback --no-secmem-warning -u "%{_gpg_name}" -sbo %{__signature_filename} --digest-algo sha256 %{__plaintext_filename}
EOF
        log "Signing rpms"
        HOME="$rpmhome" rpm --addsign "$RPM_OUT_DIR"/*.rpm \
            || die "rpm --addsign failed"
    else
        log "POSTHOGOS_PACKAGER_KEY unset → UNSIGNED rpms + repo (dnf needs gpgcheck=0)"
    fi

    log "Generating repodata (createrepo_c)"
    createrepo_c --quiet "$RPM_OUT_DIR"

    if [ "$signed" = 1 ]; then
        log "Signing repomd.xml (repo_gpgcheck)"
        gpg --batch --yes --pinentry-mode loopback \
            --default-key "$POSTHOGOS_PACKAGER_KEY_FPR" \
            --detach-sign --armor -o "$RPM_OUT_DIR/repodata/repomd.xml.asc" \
            "$RPM_OUT_DIR/repodata/repomd.xml"
        gpg --batch --armor --export "$POSTHOGOS_PACKAGER_KEY_FPR" \
            > "$RPM_OUT_DIR/RPM-GPG-KEY-posthogos"
        rm -rf "$GNUPGHOME"; unset GNUPGHOME
    fi

    # Drop-in repo file (gpgcheck on only when we actually signed).
    local gc=1; [ "$signed" = 1 ] || gc=0
    cat > "$RPM_OUT_DIR/posthogos.repo" <<EOF
[posthogos]
name=PosthogOS
baseurl=https://posthog.github.io/linux-posthogos/rpm
enabled=1
gpgcheck=$gc
repo_gpgcheck=$gc
gpgkey=https://posthog.github.io/linux-posthogos/rpm/RPM-GPG-KEY-posthogos
EOF

    log "dnf repo ready at $RPM_OUT_DIR"
    find "$RPM_OUT_DIR" -type f | sort | sed 's/^/    /'
}

main "$@"
